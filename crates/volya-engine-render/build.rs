//! Translates every program's WGSL to WebGL 2's GLSL ES 3.00 with naga (the
//! coordinate space adjusted, the point size written, bounds unchecked,
//! overrides processed; docs/architecture/rendering.md, Shaders). Writes
//! `shaders.rs` into `OUT_DIR`: each entry point's source with its
//! combined samplers and uniform blocks by name and resource binding.

use std::fmt::Write as _;
use std::path::PathBuf;

use naga::back::glsl;
use naga::valid::{Capabilities, ValidationFlags, Validator};

/// The programs, by module name.
const MODULES: [&str; 8] = [
    "ui",
    "yuv",
    "sky",
    "particle",
    "ramp",
    "postprocess",
    "details",
    "world",
];

fn binding(module: &naga::Module, var: naga::Handle<naga::GlobalVariable>) -> (u32, u32) {
    let b = module.global_variables[var]
        .binding
        .as_ref()
        .expect("a resource has a binding");
    (b.group, b.binding)
}

fn main() {
    let out = PathBuf::from(std::env::var_os("OUT_DIR").expect("OUT_DIR"));
    let mut code = String::from(
        "// Generated by build.rs from the programs' WGSL: do not edit.\n\
         pub static STAGES: &[Stage] = &[\n",
    );
    for name in MODULES {
        let path = format!("src/{name}.wgsl");
        println!("cargo::rerun-if-changed={path}");
        let source = std::fs::read_to_string(&path).expect("reads the program");
        let module = naga::front::wgsl::parse_str(&source)
            .unwrap_or_else(|e| panic!("{path}: {}", e.emit_to_string(&source)));
        // WebGL 2 offers none of naga's optional capabilities.
        let info = Validator::new(ValidationFlags::all(), Capabilities::empty())
            .validate(&module)
            .unwrap_or_else(|e| panic!("{path}: {e:?}"));
        let options = glsl::Options {
            version: glsl::Version::Embedded {
                version: 300,
                is_webgl: true,
            },
            writer_flags: glsl::WriterFlags::ADJUST_COORDINATE_SPACE
                | glsl::WriterFlags::FORCE_POINT_SIZE,
            ..Default::default()
        };
        for entry in &module.entry_points {
            let (module, info) = naga::back::pipeline_constants::process_overrides(
                &module,
                &info,
                Some((entry.stage, &entry.name)),
                &naga::back::PipelineConstants::default(),
            )
            .unwrap_or_else(|e| panic!("{path} {}: {e}", entry.name));
            let pipeline = glsl::PipelineOptions {
                shader_stage: entry.stage,
                entry_point: entry.name.clone(),
                multiview: None,
            };
            let policies = naga::proc::BoundsCheckPolicies {
                index: naga::proc::BoundsCheckPolicy::Unchecked,
                buffer: naga::proc::BoundsCheckPolicy::Unchecked,
                image_load: naga::proc::BoundsCheckPolicy::Unchecked,
                binding_array: naga::proc::BoundsCheckPolicy::Unchecked,
            };
            let mut glsl = String::new();
            let reflection =
                glsl::Writer::new(&mut glsl, &module, &info, &options, &pipeline, policies)
                    .and_then(|mut w| w.write())
                    .unwrap_or_else(|e| panic!("{path} {}: {e}", entry.name));
            let mut textures: Vec<_> = reflection
                .texture_mapping
                .iter()
                .map(|(glsl_name, m)| {
                    (
                        glsl_name.clone(),
                        binding(&module, m.texture),
                        m.sampler.map(|s| binding(&module, s)),
                    )
                })
                .collect();
            textures.sort();
            let mut blocks: Vec<_> = reflection
                .uniforms
                .iter()
                .map(|(&var, glsl_name)| (glsl_name.clone(), binding(&module, var)))
                .collect();
            blocks.sort();
            let vertex = entry.stage == naga::ShaderStage::Vertex;
            write!(
                code,
                "    Stage {{ module: {name:?}, entry: {:?}, vertex: {vertex}, source: {glsl:?}, textures: &[",
                entry.name
            )
            .unwrap();
            for (n, t, s) in &textures {
                write!(
                    code,
                    "Sampled {{ name: {n:?}, texture: {t:?}, sampler: {s:?} }}, "
                )
                .unwrap();
            }
            code.push_str("], blocks: &[");
            for (n, b) in &blocks {
                write!(code, "Block {{ name: {n:?}, binding: {b:?} }}, ").unwrap();
            }
            code.push_str("] },\n");
        }
    }
    code.push_str("];\n");
    std::fs::write(out.join("shaders.rs"), code).expect("writes shaders.rs");
}
